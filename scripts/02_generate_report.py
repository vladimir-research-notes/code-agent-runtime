#!/usr/bin/env python3
"""Run the default eval suite and generate result/report artifacts (Milestone 8).

Runs every task under ``tasks/`` across the deterministic mock/scripted/probe
agents, then writes, under ``results/`` (gitignored):

    results/raw/eval.json        — the machine-readable suite result
    results/reports/eval.md      — the Markdown report
    results/reports/eval.html    — the standalone HTML report

and prints the Markdown report to stdout. CPU-only and offline; no paid API. The
canonical, committed result table lives in ``docs/RESULTS.md``; these artifacts
are reproducible blobs, regenerated by re-running this script.

    python3 scripts/02_generate_report.py [--dir tasks] [--no-sandbox]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from code_agent_runtime import reports as _reports  # noqa: E402
from code_agent_runtime import scoring as _scoring  # noqa: E402
from code_agent_runtime import tasks as _tasks  # noqa: E402
from code_agent_runtime.runtime import RunConfig  # noqa: E402


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dir", default=str(ROOT / "tasks"), help="Tasks directory.")
    parser.add_argument("--out", default=str(ROOT / "results"), help="Output directory.")
    parser.add_argument("--no-sandbox", action="store_true", help="Disable sandbox enforcement.")
    args = parser.parse_args(argv)

    tasks = list(_tasks.discover_tasks(args.dir, resolve_fixture=True))
    if not tasks:
        print(f"No tasks found under {args.dir}/.", file=sys.stderr)
        return 1

    config = RunConfig(enforce_sandbox=not args.no_sandbox)
    suite = _scoring.run_suite(tasks, config=config, label=f"dir={args.dir}")

    out = Path(args.out)
    raw = _scoring.write_suite_result(suite, out / "raw" / "eval.json")
    md_path = out / "reports" / "eval.md"
    html_path = out / "reports" / "eval.html"
    md_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.write_text(_reports.suite_to_markdown(suite), encoding="utf-8")
    html_path.write_text(_reports.suite_to_html(suite), encoding="utf-8")

    print(_reports.suite_to_markdown(suite))
    totals = suite.totals()
    print(
        f"\nwrote: {raw}, {md_path}, {html_path}\n"
        f"{suite.total} run(s): {totals['passed']} passed, {totals['failed']} failed, "
        f"{totals['not_scored']} not scored, {totals['error']} errored.",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
