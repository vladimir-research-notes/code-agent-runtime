"""Standalone HTML report for a suite result (Milestone 8).

Renders a :class:`~code_agent_runtime.scoring.SuiteResult` as a single,
self-contained HTML document (inline CSS, no external assets) so it can be opened
directly or dropped into the website. It mirrors the Markdown report's table and
notes; result cells are colour-coded by verdict for quick scanning.
"""

from __future__ import annotations

from html import escape

from ..scoring import Outcome, SuiteResult
from .markdown import verdict_label

_STYLE = """\
body { font: 15px/1.5 system-ui, -apple-system, Segoe UI, Roboto, sans-serif;
       max-width: 60rem; margin: 2rem auto; padding: 0 1rem; color: #1b1f24; }
h1 { font-size: 1.5rem; } h2 { font-size: 1.15rem; margin-top: 1.5rem; }
table { border-collapse: collapse; width: 100%; margin: 1rem 0; font-size: 14px; }
th, td { border: 1px solid #d0d7de; padding: 0.35rem 0.6rem; text-align: left; }
th { background: #f6f8fa; }
.pass { color: #0a7d33; font-weight: 600; }
.fail { color: #b62324; font-weight: 600; }
.muted { color: #6e7781; }
.summary { font-size: 1.05rem; }
code { background: #f6f8fa; padding: 0 0.25rem; border-radius: 3px; }
footer { margin-top: 2rem; color: #6e7781; font-size: 13px; }
"""

_COLUMNS = (
    "task id",
    "agent",
    "method",
    "result",
    "runtime (s)",
    "tool calls",
    "commands",
    "failure reason",
)


def _verdict_html(rec) -> str:
    label = verdict_label(rec)
    if rec.passed is True:
        return f'<span class="pass">{escape(label)}</span>'
    if rec.passed is False:
        return f'<span class="fail">{escape(label)}</span>'
    return f'<span class="muted">{escape(label)}</span>'


def suite_to_html(suite: SuiteResult, *, title: str = "Evaluation results") -> str:
    """Render ``suite`` as a standalone HTML document string."""
    totals = suite.totals()
    head = (
        "<thead><tr>"
        + "".join(f"<th>{escape(c)}</th>" for c in _COLUMNS)
        + "</tr></thead>"
    )
    rows = []
    for rec in suite.records:
        cells = [
            f"<code>{escape(rec.task_id)}</code>",
            escape(rec.agent),
            escape(str(rec.score.get("method", ""))),
            _verdict_html(rec),
            f"{rec.runtime_seconds:.3f}",
            str(rec.tool_call_count),
            str(rec.command_count),
            escape(rec.failure_reason or ""),
        ]
        rows.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    table = f"<table>{head}<tbody>{''.join(rows)}</tbody></table>"

    skipped_html = ""
    if suite.skipped:
        items = "".join(
            f"<li><code>{escape(s.get('agent', ''))}</code> on "
            f"<code>{escape(s.get('task_id', ''))}</code></li>"
            for s in suite.skipped
        )
        skipped_html = f"<h2>Skipped (agent not applicable to task)</h2><ul>{items}</ul>"

    label_html = f"<p class='muted'>Suite: {escape(suite.label)}</p>" if suite.label else ""
    summary = (
        f"<p class='summary'><strong>{suite.total} run(s)</strong> — "
        f"{totals[Outcome.PASSED]} passed, {totals[Outcome.FAILED]} failed, "
        f"{totals[Outcome.NOT_SCORED]} not scored, {totals[Outcome.ERROR]} errored.</p>"
    )
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)} — Code Agent Runtime</title>
<style>{_STYLE}</style>
</head>
<body>
<h1>{escape(title)}</h1>
{label_html}
{summary}
{table}
{skipped_html}
<h2>Notes</h2>
<ul>
<li><code>result</code> is the scored verdict: <code>pass</code>/<code>fail</code>,
or <code>not_scored</code> for tasks scored by inspection.</li>
<li>A passing test command is evidence, not proof, of correctness;
<code>diff_constraint</code> checks scope, not correctness.</li>
<li>Runtime is wall-clock and machine-dependent; tool/command counts are
deterministic and reproducible.</li>
</ul>
<footer>Generated by Code Agent Runtime — reports/html.py</footer>
</body>
</html>
"""
